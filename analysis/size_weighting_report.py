"""The size-weighting report (analysis/SIZE_WEIGHTING_PLAN.md step S5), built only from checkpoints.

For each dataset × arm × model, every finished weighted run is set against the cached unweighted
baseline on the same folds:
- overall MAE (the unweighted guardrail) and a size-balanced MAPE (mean of the per-band MAPEs), each as a
  fold-paired difference ± SE;
- per size band: median residual % (bias; + = the model overprices) and MAPE;
- V4's fitted size power per class;
- how V4's corps-8 values move per band (weighted ÷ unweighted), to compare with what size
  harmonisation does (analysis/output/teams/value_bases.md);
- the ladder-replay test on ToW cards: does the part of value the weighting removes predict winning?
  (Full harmonisation's removed part did: +0.32, z 3.0.)

    py -3.13 analysis/size_weighting.py report
"""

from __future__ import annotations

import pickle

import numpy as np

import size_weighting as sw
import team_values as tv
import unit_pricing as up
from blind_ideas import FINAL

MODES = (("V4", "fixed"), ("V4", "nested"), ("F6", "full"))


def runs_for(dataset: str, arm: str) -> dict[tuple[str, str, str], dict]:
    out = {}
    for model, mode in MODES:
        for variant in sw.VARIANTS:
            path = sw.checkpoint(dataset, arm, model, mode, variant)
            if path.exists():
                out[(model, mode, variant)] = pickle.loads(path.read_bytes())
    return out


def fold_scores(units: list[up.Unit], kind: str, run: up.CVRun) -> np.ndarray:
    """Per fold: [MAE, balanced MAPE] of the out-of-fold predictions."""
    band, labels = sw.bands_of(units, kind)
    cost = np.array([u.cost for u in units], float)
    scores = []
    for k in sorted(set(run.oof_fold.tolist()) - {0}):
        m = (run.oof_fold == k) & np.isfinite(run.oof)
        ape = np.abs(run.oof - cost) / cost * 100
        per_band = [ape[m & (band == b)].mean() for b in range(len(labels)) if (m & (band == b)).sum() > 0]
        scores.append([np.abs(run.oof[m] - cost[m]).mean(), np.mean(per_band)])
    return np.array(scores)


def paired(base: np.ndarray, new: np.ndarray, col: int) -> str:
    d = new[:, col] - base[:, col]
    return f"{new[:, col].mean():.2f} ({d.mean():+.2f} ± {d.std(ddof=1) / np.sqrt(len(d)):.2f})"


def value_ratio_by_band(dataset: str, arm: str, units: list[up.Unit], fitted) -> dict[str, float]:
    base, _ = tv.v4_raw_and_oof(dataset, arm, units)
    new, _ = tv.v4_raw_and_oof(dataset, arm, units, fitted)
    band, labels = sw.bands_of(units, FINAL[arm].size)
    keys = [(u.faction, u.key) for u in units]
    ratio = np.array([new[k] / base[k] for k in keys])
    return {labels[b]: float(np.median(ratio[band == b])) for b in range(len(labels)) if (band == b).sum() > 0}


def replay(fitted_by_variant: dict[str, dict[str, tuple]]) -> list[list[str]]:
    """ToW cards (units + commanders) valued by the baseline V4 (raw) and each weighted V4."""
    vals: dict[str, dict] = {"raw": {}}
    units_all: list[up.Unit] = []
    for arm in sw.ARMS:
        units = tv.slice_of("tow", arm).units
        units_all += units
        vals["raw"].update(tv.v4_raw_and_oof("tow", arm, units)[0])
        for variant, by_arm in fitted_by_variant.items():
            vals.setdefault(variant, {}).update(tv.v4_raw_and_oof("tow", arm, units, by_arm[arm])[0])
    versions = tuple(v for v in vals if v != "raw")
    cards = {(u.faction, u.key): {"cost": float(u.cost), **{v: vals[v][(u.faction, u.key)] for v in vals}}
             for u in units_all}
    cmd = {v: tv.commander_values(None, None, vals[v]) for v in vals}
    for k in cmd["raw"]:
        if all(k in cmd[v] for v in versions):
            cards[k] = {"cost": _commander_price(k), **{v: cmd[v][k] for v in vals}}
    return tv.replay_test(cards, versions)


_PRICES: dict[tuple[str, str], float] = {}


def _commander_price(key: tuple[str, str]) -> float:
    if not _PRICES:
        import commander_model as cm
        for r in cm.Pairs().rows:
            _PRICES[(r["faction_key"], r["commander_unit_key"])] = float(r["commander_price"])
    return _PRICES[key]


def main(started: float) -> None:
    L = ["# Size-frequency weighting — report (generated by analysis/size_weighting_report.py)", "",
         "Weighted refits against the cached unweighted fits, same folds. Variants: "
         + ", ".join(f"`{k}` = α {v['alpha']}, cap {v['cap'] or 'none'}" for k, v in sw.VARIANTS.items())
         + ". MAE in gold; balanced MAPE = mean of the per-size-band MAPEs; (Δ ± paired SE over the 5 folds). "
         "Bias = median residual % (+ = the model overprices). V4 `fixed` keeps the unweighted size powers, "
         "`nested` searches them again under the weights.", ""]
    nested_tow: dict[str, dict[str, tuple]] = {}
    for dataset in sw.DATASETS:
        for arm in sw.ARMS:
            sl = tv.slice_of(dataset, arm)
            units, kind = sl.units, FINAL[arm].size
            found = runs_for(dataset, arm)
            if not found:
                continue
            L += [f"## {dataset.upper()} {arm}", "", "| model | variant | ESS | MAE | balanced MAPE | worst |bias| |",
                  "|---|---|---|---|---|---|"]
            bases = {"V4": sw.baseline_v4(dataset, arm)[0], "F6": sw.baseline_f6(dataset, arm)[0]}
            base_scores = {m: fold_scores(units, kind, r) for m, r in bases.items()}
            for m, r in bases.items():
                worst = max(abs(b["bias"]) for b in sw.band_errors(units, kind, r.oof))
                L.append(f"| {m} | unweighted | {len(units)} | {base_scores[m][:, 0].mean():.2f} | "
                         f"{base_scores[m][:, 1].mean():.2f} | {worst:.1f}% |")
            for (model, mode, variant), res in found.items():
                sc = fold_scores(units, kind, res["run"])
                worst = max(abs(b["bias"]) for b in sw.band_errors(units, kind, res["run"].oof))
                L.append(f"| {model} {mode} | {variant} | {res['ess']:.0f} | {paired(base_scores[model], sc, 0)} | "
                         f"{paired(base_scores[model], sc, 1)} | {worst:.1f}% |")
            # Per-band bias / MAPE, V4 (nested where available, else fixed) and F6.
            for model in ("V4", "F6"):
                cols = [("unweighted", bases[model])]
                for variant in sw.VARIANTS:
                    res = found.get((model, "nested", variant)) or found.get((model, "fixed", variant)) \
                        or found.get((model, "full", variant))
                    if res:
                        cols.append((variant, res["run"]))
                if len(cols) == 1:
                    continue
                tables = [{b["band"]: b for b in sw.band_errors(units, kind, r.oof)} for _, r in cols]
                L += ["", f"**{model} by size band** (bias % / MAPE %)", "",
                      "| band | units | " + " | ".join(name for name, _ in cols) + " |",
                      "|---|---|" + "---|" * len(cols)]
                for band in tables[0]:
                    L.append(f"| {band} | {tables[0][band]['units']} | " + " | ".join(
                        f"{t[band]['bias']:+.1f} / {t[band]['mape']:.1f}" if band in t else "" for t in tables) + " |")
            # V4 size powers and value shifts.
            nested = {v: found[("V4", "nested", v)] for v in sw.VARIANTS if ("V4", "nested", v) in found}
            if nested:
                base_p = sw.baseline_v4(dataset, arm)[1]
                L += ["", "**V4 size power per class** (unweighted → " + ", ".join(nested) + ")", ""]
                for seg in sorted(base_p):
                    L.append(f"- {seg}: {base_p[seg]:.2f} → " + ", ".join(
                        f"{r['extra']['p_of'].get(seg, float('nan')):.2f}" for r in nested.values()))
                L += ["", "**V4 corps-8 value, weighted ÷ unweighted, median per band**", "",
                      "| variant | " + " | ".join(sw.bands_of(units, kind)[1]) + " |",
                      "|---|" + "---|" * len(sw.bands_of(units, kind)[1])]
                for variant, res in nested.items():
                    ratio = value_ratio_by_band(dataset, arm, units, (res["run"], res["extra"]["p_of"]))
                    L.append(f"| {variant} | " + " | ".join(f"×{ratio[b]:.3f}" if b in ratio else ""
                                                             for b in sw.bands_of(units, kind)[1]) + " |")
                    if dataset == "tow":
                        nested_tow.setdefault(variant, {})[arm] = (res["run"], res["extra"]["p_of"])
            L.append("")
            up.log(f"report: {dataset} {arm}", started)
    complete = {v: by_arm for v, by_arm in nested_tow.items() if set(by_arm) == set(sw.ARMS)}
    if complete:
        L += ["## Ladder replays (ToW cards, nested V4)", "",
              "Logistic regression on wins as in team_values.py: each version's value surplus, and the part the "
              "weighting removes from the unweighted value. A positive, significant 'removed part' means the "
              "weighting throws away something that predicts winning (full harmonisation: +0.32, z 3.0).", "",
              "| version | value surplus β | removed part β | sd of removed part |", "|---|---|---|---|"]
        for row in replay(complete):
            L.append("| " + " | ".join(row) + " |")
        L.append("")
    (sw.OUT / "size_weighting_report.md").write_text("\n".join(L), encoding="utf-8")
    up.log("report → analysis/output/size_weighting_report.md", started)
